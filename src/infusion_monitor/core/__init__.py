"""M2 主路径内核：可插拔预测器协议 + 确定性几何核 + 逐帧传播。

分层结构，业务层只认最上面那层的协议：

* :mod:`.predictor` —— 「给点/框 → 出掩膜」的协议，生产权重与几何核共用；
* :mod:`.predictor_contract` —— **一套断言、两个实现都跑**的协议契约（含掩膜 PNG 往返口径），
  换实现后用它证明新实现没有破坏 dtype/shape/坐标系/退化输入这四条；
* :mod:`.config_map` —— ``model_id → (配置文件, 权重)`` 映射表 + 预测器注册表，业务层取
  预测器的唯一入口是 :func:`~.config_map.build_predictor`（缺权重即报错，不静默退回几何核）；
* :mod:`.weights_predictor` —— 生产权重加载入口（读配置 → 验权重 → 交适配器）；
* :mod:`.geom_kernel` —— 确定性几何核实现（无权重时的基线，也是模型降级路径）；
* :mod:`.postprocess` —— 掩膜几何后处理（连通域、形态特征、孔洞/孤岛、粘连分离）；
* :mod:`.enumerate` —— 首帧无提示枚举（护士在列表里认领，而不是逐袋点像素）；
* :mod:`.memory_bank` —— top-k 记忆库（帧号 + 掩膜 + 置信），相似度加权参与本帧判断；
* :mod:`.occlusion` —— 可见度状态机（visible/partial/occluded/reappeared/lost）与轨迹交出；
* :mod:`.reacquire` —— 交出之后的局部重枚举再获取（接回原 ``bag_seq``，不新建轨迹）；
* :mod:`.propagate` —— 起锚 → 记住 → 传播，把掩膜接成面积比曲线；
* :mod:`.multi_object` —— 多袋并行（一个状态、一遍传播）与槽位-轨迹分配（哪条曲线是哪只袋子）；
* :mod:`.tracking` —— 帧间关联与轨迹 ID 管理（只做关联，不重新分割）；
* :mod:`.smoothing` —— 面积序列平滑（中值 + 一阶平滑）、物理单调约束与缺帧受限重建；
* :mod:`.failure_modes` —— 拍摄质量分类（六类失败模式 + 中文补拍建议；只降级标记，从不拒绝）。
"""

